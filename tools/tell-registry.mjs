// Collect feature-owned tell data. The browser reads generated ESM; Node tools and servers regenerate it before use.
import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';import{fileURLToPath}from'node:url';
const ROOT=fileURLToPath(new URL('..',import.meta.url));
const FIELDS={thrown:'THROWN',quiet:'QUIET',byHand:'BY_HAND',answers:'ANSWER',heights:'HEIGHT',harmless:'HARMLESS'};
const SETS=new Set(['thrown','quiet','harmless']);
export function readTellFeatures(root=ROOT){
 const out=Object.fromEntries(Object.keys(FIELDS).map(k=>[k,new Map()]));
 for(const file of readdirSync(join(root,'src/tells')).filter(f=>f.endsWith('.json')).sort()){
  const data=JSON.parse(readFileSync(join(root,'src/tells',file),'utf8'));
  for(const key of Object.keys(data))if(!(key in FIELDS)&&key!=='notes')throw Error('unknown tell field '+key+' in '+file);
  for(const key of Object.keys(FIELDS))if(data[key]!==undefined){
   if(SETS.has(key)!==Array.isArray(data[key])||typeof data[key]!=='object'||data[key]===null)throw Error('invalid '+key+' in '+file);
   for(const[k,v]of SETS.has(key)?data[key].map(k=>[k,true]):Object.entries(data[key])){
    if(typeof k!=='string'||!k||(!SETS.has(key)&&typeof v!=='string'))throw Error('invalid tell entry in '+file);
    if(key==='byHand'&&!['','!','!!'].includes(v))throw Error('invalid mark in '+file);
    if(key==='answers'&&!['block','dodge','jump','duck'].includes(v))throw Error('invalid answer in '+file);
    if(key==='heights'&&!['high','low'].includes(v))throw Error('invalid height in '+file);
    if(out[key].has(k))throw Error('duplicate '+key+' tell '+k+' in '+file);
    out[key].set(k,v);
   }
  }
 }
 return Object.fromEntries(Object.entries(out).map(([key,rows])=>[key,SETS.has(key)?[...rows.keys()].sort():Object.fromEntries([...rows].sort(([a],[b])=>a.localeCompare(b)))]));
}
export function writeTellRegistry(root=ROOT,{check=false}={}){
 const data=readTellFeatures(root),path=join(root,'src/tells/data.generated.js');
 const text='// Generated by tools/registries.mjs from src/tells/*.json. Never edit by hand.\n'+Object.entries(FIELDS).map(([key,name])=>
  'export const '+name+' = '+(SETS.has(key)?'new Set('+JSON.stringify(data[key],null,2)+')':JSON.stringify(data[key],null,2))+';').join('\n')+'\n';
 const same=existsSync(path)&&readFileSync(path,'utf8').replace(/\r\n/g,'\n')===text;
 if(check&&!same)throw Error('tell registry is stale: run node tools/registries.mjs');
 if(!check&&!same)writeFileSync(path,text);
 return data;
}
