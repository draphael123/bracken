// tools/map-plates-solve.mjs - SOLVES WHERE EVERY NODE'S NAME BOARD SITS ON THE WORLD MAP (claude/mapscale) and writes src/map-plate-spots.js.
// The runtime layout (src/map-plates.js layoutPlates) puts boards on the first free side and nudges the worst; the crowded corners (Hexed Fields / Burial Caverns /
// Stormhold ...) need the info card kept clear as well, which is a search. This is that search, run once offline, seeded (the same table every run): simulated annealing over
// every board's spot, cost = boards over nodes / signposts / landmarks / each other / their own node + info cards that would hide a board they must keep clear.
// Re-run it when a node is added or moved (tools/map-scale.mjs says so):  node tools/map-plates-solve.mjs   (about a minute).
import fs from 'node:fs';
import vm from 'node:vm';
import { LEVELS } from '../src/level.js';
import * as M from '../src/map-plates.js';
const lf = u => fs.readFileSync(new URL(u, import.meta.url), 'utf8').split(String.fromCharCode(13)).join('');
const ctx = vm.createContext({ LEVELS });
const main = lf('../src/main.js'); vm.runInContext(main.slice(main.indexOf('const MAPW ='), main.indexOf('const MAPC =')) + '\nglobalThis.route = { NODES };', ctx);
const nodes = M.plateNodes(ctx.route.NODES, n => LEVELS[n.level].name), N = nodes.length, VW = 320;
const out = M.layoutPlates(nodes, VW);                       /* the table in place now is applied first; start from what the runtime would draw */
const boxes = nodes.map(M.nodeBox), signs = nodes.map(M.signBox), lms = M.landmarkRects(nodes);
const nearOf = nodes.map((nd, i) => nodes.map((m, j) => j).filter(j => Math.hypot(nodes[j].x - nd.x, nodes[j].y - nd.y) < 190));
const lmsOf = nodes.map(nd => lms.filter(r => Math.hypot(r.x + r.w / 2 - nd.x, r.y + r.h / 2 - nd.y) < 150));
const plates = nodes.map(n => ({ ...out.get(n.id) }));
const live = new Map(nodes.map((n, i) => [n.id, plates[i]]));       /* what placePanel reads */
const geo = i => M.plateCost(plates[i], i, nodes, boxes, signs, lmsOf[i], plates, nearOf[i]);
const geoNear = i => nearOf[i].reduce((s, j) => s + geo(j), 0);
const aff = nodes.map((nd, i) => nodes.filter(n => n.id === nd.id || M.neighbours(n, nodes).includes(nd.id)));
const ok = n => M.placePanel(n, nodes, live, M.SCREEN, true).ok;
const cands = nodes.map(nd => M.plateCandidates(nd, VW));
let seed = 20261009; const rnd = () => { seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const okCount = i => aff[i].filter(n => !ok(n)).length;
let bad0 = nodes.filter(n => !ok(n)).length, g0 = nodes.reduce((s, _, i) => s + geo(i), 0);
console.log('start: geometry cost ' + g0.toFixed(0) + ', cards hiding something: ' + bad0);
const ITER = +(process.env.ITER || 40000);
for (let it = 0; it < ITER; it++) {
  const T = 40 * Math.pow(0.5 / 40, it / ITER), i = Math.floor(rnd() * N), list = cands[i], p = list[Math.floor(rnd() * list.length)], cur = plates[i];
  const was = { x: cur.x, y: cur.y, w: cur.w, h: cur.h }, before = geoNear(i), failBefore = okCount(i);
  Object.assign(cur, p); const after = geoNear(i), d = after - before, thr = -T * Math.log(rnd() + 1e-9);
  if (failBefore === 0 && d > thr) { Object.assign(cur, was); continue; }      /* the panel can only make it worse: skip the expensive part */
  const dTotal = d + 800 * (okCount(i) - failBefore);
  if (dTotal > thr) Object.assign(cur, was);
}
nodes.forEach((n, i) => Object.assign(live.get(n.id), plates[i]));
const bad1 = nodes.filter(n => !ok(n)).length, g1 = nodes.reduce((s, _, i) => s + geo(i), 0);
console.log('end:   geometry cost ' + g1.toFixed(0) + ', cards hiding something: ' + bad1);
const lines = nodes.map((n, i) => '  ' + JSON.stringify(n.id) + ': [' + [plates[i].x - n.x, plates[i].y - n.y, plates[i].w, plates[i].h].join(', ') + '],');
fs.writeFileSync(new URL('../src/map-plate-spots.js', import.meta.url), '// src/map-plate-spots.js - GENERATED by tools/map-plates-solve.mjs (claude/mapscale): [dx, dy, w, h] of each node\'s name board from its node. Do not edit by hand;\r\n// re-run the solver when a node is added or moved (tools/map-scale.mjs says so).\r\nexport const PLATE_SPOTS = {\r\n' + lines.join('\r\n') + '\r\n};\r\n');
console.log('wrote src/map-plate-spots.js (' + N + ' boards)');
