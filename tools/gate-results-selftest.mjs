// Failure injection for gate coverage: no missing artifact, duplicate, stale SHA or incomplete run can turn green.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { annotations, assignShards, formatSummary, mergeReports } from './gate-results.mjs';
import { parentLives } from './process-owner.mjs';
const procs = new Map([[1, { pid: 1 }], [7, { pid: 7, born: 100 }], [8, { pid: 8, born: 300 }]]);
assert.equal(parentLives({ ppid: 1 }, procs, 'linux'), false, 'init adoption is an orphan, not a living owner');
assert.equal(parentLives({ ppid: 7, born: 200 }, procs, 'linux'), true);
assert.equal(parentLives({ ppid: 8, born: 200 }, procs, 'win32'), false, 'reused parent PID is not the original owner');
assert.equal(parentLives({ ppid: 9 }, procs, 'linux'), false);
const names = ['a', 'b', 'new-check', 'syntax'], timings = { a: 100, b: 90, syntax: 10, retired: 999999 };
const assigned = assignShards(names, timings, 2);
assert.equal(assigned.size, 4); assert.equal(assigned.has('retired'), false);
assert.deepEqual([...assigned], [...assignShards([...names].reverse(), timings, 2)]);
const plan = { commit: 'sha', count: 2, names, shards: [1, 2].map(id => ({ names: names.filter(n => assigned.get(n) === id) })) };
const row = name => ({ name, ok: name !== 'b', ms: 10, last: '100%\nFAIL child', out: ['FAIL child', 'detail'] });
const reports = plan.shards.map((s, i) => ({ schema: 1, commit: 'sha', shard: [i + 1, 2], expected: s.names, complete: true, results: s.names.map(row) }));
assert.deepEqual(mergeReports(plan, reports), names.map(row));
assert.match(formatSummary(names.map(row)), /\n1 check\(s\) failed\.$/);
assert.match(formatSummary(names.map(row)), /\n  FAIL child\n  detail/);
assert.match(annotations([row('b')])[0], /100%25%0AFAIL child/);
const many = Array.from({ length: 30 }, (_, i) => ({ ...row('red-' + i), ok: false })), notes = annotations(many);
assert.ok(notes.length <= 9);
for (const r of many) assert.ok(notes[0].includes('FAIL ' + r.name + ' '), 'every red must be visible before the annotation cap');
assert.throws(() => mergeReports(plan, [reports[0], reports[0]]), /duplicate shard/);
assert.throws(() => mergeReports(plan, [{ ...reports[0], commit: 'stale' }]), /identity/);
assert.throws(() => mergeReports(plan, [{ ...reports[0], expected: [] }]), /inventory/);
assert.throws(() => mergeReports(plan, [{ ...reports[0], results: [row('not-registered')] }]), /invalid/);
assert.equal(mergeReports(plan, []).filter(r => !r.ok).length, 5);
const interrupted = mergeReports(plan, [{ ...reports[0], complete: false, results: [] }, reports[1]]);
assert.equal(interrupted.at(-1).name, 'gate-infrastructure');
assert.ok(interrupted.some(r => r.last.startsWith('NO VERDICT')));
const list = spawnSync(process.execPath, ['tools/check.mjs', '--list'], { encoding: 'utf8', cwd: new URL('..', import.meta.url) });
assert.equal(list.status, 0, list.stderr);
const inventory = JSON.parse(list.stdout);
assert.equal(inventory.length, new Set(inventory).size);
for (const required of ['syntax', 'textfit-full', 'textfit-levelcard', 'profile-cleanup', 'profile-leaks']) assert.ok(inventory.includes(required), required);
console.log('ok gate-results: deterministic full coverage, interrupted/missing shards fail, stale/duplicate receipts rejected, detail format preserved; ' + inventory.length + ' registered checks');
